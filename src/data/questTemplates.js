export const ALL_QUESTS = QUEST_CATEGORIES.flatMap(cat =>
  cat.quests.map(q => ({ ...q, categoryId: cat.id, categoryLabel: cat.label, categoryColor: cat.color }))
);

export function searchQuests(query) {
  if (!query.trim()) return ALL_QUESTS;
  const q = query.toLowerCase();
  return ALL_QUESTS.filter(quest =>
    quest.title.toLowerCase().includes(q) ||
    quest.notes?.toLowerCase().includes(q)
  );
}
